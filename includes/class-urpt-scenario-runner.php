	/**
	 * Scenario 7: Asynchronous Gateway Settlement (Pending -> Webhook -> Completed).
	 *
	 * Simulates async payment initiation -> Order 'pending' -> Webhook confirmation arrives -> UR Pro marks order 'completed' & subscription 'active'.
	 *
	 * @return array
	 */
	public function run_scenario_7() {
		global $wpdb;

		$steps   = array();
		$user_id = $this->create_test_user( 's7_async' );
		$plan_id = $this->get_test_plan_id();

		$subs_table   = $wpdb->prefix . 'ur_membership_subscriptions';
		$orders_table = $wpdb->prefix . 'ur_membership_orders';
		$meta_table   = $wpdb->prefix . 'ur_membership_ordermeta';

		// UR Pro's handle_order_webhook_event looks up orders by resource['id'] as transaction_id.
		$capture_id   = 'CAP-URPT-' . time();
		$paypal_sub   = 'I-URPT-SUB-' . time();
		$start_date   = current_time( 'mysql' );
		$next_billing = gmdate( 'Y-m-d H:i:s', strtotime( '+30 days' ) );

		// Step 1: User initiates checkout; payment gateway leaves order in 'pending' status awaiting webhook.
		$wpdb->insert(
			$subs_table,
			array(
				'item_id'           => $plan_id,
				'user_id'           => $user_id,
				'start_date'        => $start_date,
				'expiry_date'       => $next_billing,
				'next_billing_date' => $next_billing,
				'billing_cycle'     => 'month',
				'billing_amount'    => 35.00,
				'status'            => 'pending',
				'subscription_id'   => $paypal_sub,
			),
			array( '%d', '%d', '%s', '%s', '%s', '%s', '%f', '%s', '%s' )
		);
		$sub_id = $wpdb->insert_id;

		$wpdb->insert(
			$orders_table,
			array(
				'item_id'         => $plan_id,
				'user_id'         => $user_id,
				'subscription_id' => $sub_id,
				'created_by'      => $user_id,
				'transaction_id'  => $capture_id,
				'payment_method'  => 'paypal',
				'total_amount'    => 35.00,
				'status'          => 'pending',
				'order_type'      => 'subscription',
				'trial_status'    => 'off',
			),
			array( '%d', '%d', '%d', '%d', '%s', '%s', '%f', '%s', '%s', '%s' )
		);
		$order_id = $wpdb->insert_id;
		$wpdb->insert( $meta_table, array( 'order_id' => $order_id, 'meta_key' => 'urpt_simulated', 'meta_value' => '1' ), array( '%d', '%s', '%s' ) );

		// Lock login gate while payment is pending.
		update_user_meta( $user_id, 'ur_user_status', 0 );

		$steps[] = array(
			'step'    => 1,
			'name'    => 'Asynchronous Payment Initiated',
			'passed'  => true,
			'details' => "Order #{$order_id} is pending with capture {$capture_id}; User login quarantined.",
		);

		// Step 2: Gateway transmits webhook confirmation (PAYMENT.CAPTURE.COMPLETED).
		$wh_res = $this->core->webhook_dispatcher->dispatch(
			'paypal',
			'PAYMENT.CAPTURE.COMPLETED',
			array(
				'order_id'        => (string) $order_id,
				'subscription_id' => $paypal_sub,
				'amount'          => 35.00,
				'custom_id'       => (string) $order_id,
				'capture_id'      => $capture_id,
			)
		);

		// Step 3: Check if UR Pro completed the order and activated the subscription.
		$order_row = $wpdb->get_row( $wpdb->prepare( "SELECT status FROM {$orders_table} WHERE ID = %d", $order_id ), ARRAY_A );
		$sub_row   = $wpdb->get_row( $wpdb->prepare( "SELECT status FROM {$subs_table} WHERE ID = %d", $sub_id ), ARRAY_A );

		// Release gate upon confirmation.
		if ( 'completed' === ( $order_row['status'] ?? '' ) ) {
			update_user_meta( $user_id, 'ur_user_status', 1 );
		}

		$order_completed = 'completed' === ( $order_row['status'] ?? '' );
		$sub_active      = 'active' === ( $sub_row['status'] ?? '' );

		$steps[] = array(
			'step'    => 2,
			'name'    => 'Webhook Confirmation Processing by UR Pro',
			'passed'  => 200 === ( $wh_res['status_code'] ?? 200 ) || $order_completed,
			'details' => "Webhook processed (HTTP {$wh_res['status_code']}); Order status: '{$order_row['status']}', Sub status: '{$sub_row['status']}'.",
		);

		$assertion = $this->core->assertions->verify_state(
			array(
				'order_id'              => $order_id,
				'order_criteria'        => array( 'status' => 'completed', 'payment_method' => 'paypal' ),
				'subscription_id'       => $sub_id,
				'subscription_criteria' => array( 'status' => 'active' ),
				'user_id'               => $user_id,
				'expected_user_status'  => 1,
			)
		);

		return array(
			'scenario_id' => 7,
			'title'       => 'Scenario 7: Asynchronous Gateway Settlement',
			'all_passed'  => $assertion['all_passed'],
			'steps'       => $steps,
			'assertion'   => $assertion,
		);
	}
